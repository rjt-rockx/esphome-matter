#!/usr/bin/env python3
"""Extract mode tags, mode status codes and operational states/errors from the Matter ZAP XML.

Writes components/matter/data_model/delegate_data.json, which the delegate layer
(components/matter/delegates.py) uses to validate and encode the YAML of the Mode Base derived clusters,
Operational State and RVC Operational State.

    python tools/gen_delegate_data.py [DATA_MODEL_DIR] [OUTPUT_JSON]

DATA_MODEL_DIR defaults to the ZAP data model of the esp-matter 1.6 checkout in /home/user/refs.
"""

import json
import re
import sys
from pathlib import Path
from xml.etree import ElementTree

DEFAULT_SOURCE = Path(
    "/home/user/refs/esp-matter-1.6/connectedhomeip/connectedhomeip/src/app/zap-templates/zcl/data-model/chip"
)
DEFAULT_OUTPUT = (
    Path(__file__).resolve().parent.parent
    / "components"
    / "matter"
    / "data_model"
    / "delegate_data.json"
)

# (cluster name as in clusters.json without spaces, cluster id, xml file)
MODE_CLUSTERS = [
    ("LaundryWasherMode", 0x51, "laundry-washer-mode-cluster.xml"),
    ("RefrigeratorAndTemperatureControlledCabinetMode", 0x52,
     "refrigerator-and-temperature-controlled-cabinet-mode-cluster.xml"),
    ("RVCRunMode", 0x54, "rvc-run-mode-cluster.xml"),
    ("RVCCleanMode", 0x55, "rvc-clean-mode-cluster.xml"),
    ("DishwasherMode", 0x59, "dishwasher-mode-cluster.xml"),
    ("MicrowaveOvenMode", 0x5E, "microwave-oven-mode-cluster.xml"),
    ("OvenMode", 0x49, "oven-mode-cluster.xml"),
    ("EnergyEVSEMode", 0x9D, "energy-evse-mode-cluster.xml"),
    ("WaterHeaterMode", 0x9E, "water-heater-mode-cluster.xml"),
    ("DeviceEnergyManagementMode", 0x9F, "device-energy-management-mode-cluster.xml"),
]
OPERATIONAL_STATE_CLUSTERS = [
    ("OperationalState", 0x60, "operational-state-cluster.xml"),
    ("RVCOperationalState", 0x61, "operational-state-rvc-cluster.xml"),
    ("OvenCavityOperationalState", 0x48, "operational-state-oven-cluster.xml"),
]
# ModeBase::StatusCode, shared by all derived clusters.
BASE_STATUS_CODES = {
    "success": 0x00,
    "unsupported_mode": 0x01,
    "generic_failure": 0x02,
    "invalid_in_mode": 0x03,
}


def snake(name: str) -> str:
    name = re.sub(r"(.)([A-Z][a-z]+)", r"\1_\2", name)
    name = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    return name.lower()


def enum_items(path: Path, enum_name: str) -> dict[str, int]:
    root = ElementTree.parse(path).getroot()
    for enum in root.iter("enum"):
        if enum.get("name") == enum_name:
            return {
                snake(item.get("name")): int(item.get("value"), 0)
                for item in enum.iter("item")
            }
    return {}


def main():
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_SOURCE
    output = Path(sys.argv[2]) if len(sys.argv) > 2 else DEFAULT_OUTPUT
    data = {"_comment": "Generated by tools/gen_delegate_data.py; do not edit.",
            "mode_clusters": {}, "operational_state_clusters": {}}
    for name, cluster_id, xml in MODE_CLUSTERS:
        path = source / xml
        status = dict(BASE_STATUS_CODES)
        status.update(
            {k: v for k, v in enum_items(path, "StatusCode").items() if v >= 0x40}
        )
        data["mode_clusters"][name] = {
            "id": cluster_id,
            "tags": enum_items(path, "ModeTag"),
            "status_codes": status,
        }
    for name, cluster_id, xml in OPERATIONAL_STATE_CLUSTERS:
        path = source / xml
        data["operational_state_clusters"][name] = {
            "id": cluster_id,
            "states": enum_items(path, "OperationalStateEnum")
            or enum_items(source / "operational-state-cluster.xml", "OperationalStateEnum"),
            "errors": enum_items(path, "ErrorStateEnum")
            or enum_items(source / "operational-state-cluster.xml", "ErrorStateEnum"),
        }
    output.write_text(json.dumps(data, indent=2) + "\n")
    print(f"wrote {output}")


if __name__ == "__main__":
    main()
