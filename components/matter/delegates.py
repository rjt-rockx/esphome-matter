async def register_cluster(var, endpoint_id: int, cluster, config: dict) -> bool:
    """Registers the mapping objects of a configured delegate cluster. Returns False if there is nothing to do."""
    if cluster.name == MODE_SELECT or cluster.name in MODE_CLUSTERS:
        if CONF_MODES not in config:
            return False
        await _register_modes(var, endpoint_id, cluster, config)
        cg.add_define("USE_MATTER_MODES")
        if cluster.name == MODE_SELECT:
            # Selects the Mode Select code that needs the mode-select-server sources of esp-matter.
            cg.add_define("USE_MATTER_MODE_SELECT")
        return True
    if cluster.name in OPERATIONAL_CLUSTERS and CONF_ID in config:
        await _register_operational_state(var, endpoint_id, cluster, config)
        cg.add_define("USE_MATTER_OPERATIONAL_STATE")
        return True
    if cluster.name == LAUNDRY_WASHER_CONTROLS and (
        CONF_SPIN_SPEEDS in config or CONF_RINSES in config
    ):
        await _register_laundry_controls(var, endpoint_id, config)
        cg.add_define("USE_MATTER_LAUNDRY_CONTROLS")
        return True
    return False


async def _register_laundry_controls(var, endpoint_id, config):
    mapping = cg.new_Pvariable(config[CONF_ID], endpoint_id)
    cg.add(var.register_mapping(mapping))
    for spin_speed in config.get(CONF_SPIN_SPEEDS, []):
        cg.add(mapping.add_spin_speed(spin_speed))
    for rinse in config.get(CONF_RINSES, []):
        cg.add(mapping.add_rinse(RINSES[rinse], rinse))
    if CONF_SPIN_SPEED in config:
        cg.add(
            mapping.set_spin_speed_select(
                await cg.get_variable(config[CONF_SPIN_SPEED])
            )
        )
    if CONF_NUMBER_OF_RINSES in config:
        cg.add(
            mapping.set_rinses_select(
                await cg.get_variable(config[CONF_NUMBER_OF_RINSES])
            )
        )


async def _register_modes(var, endpoint_id, cluster, config):
    if cluster.name == MODE_SELECT:
        mapping = cg.new_Pvariable(config[CONF_ID], endpoint_id)
    else:
        mapping = cg.new_Pvariable(config[CONF_ID], endpoint_id, cluster.id)
    cg.add(var.register_mapping(mapping))
    for mode in config[CONF_MODES]:
        cg.add(mapping.add_mode(mode[CONF_LABEL], mode[CONF_MODE], mode[CONF_OPTION]))
        for tag in mode[CONF_TAGS]:
            mfg_code = tag["mfg_code"]
            cg.add(mapping.add_tag(tag["value"], mfg_code or 0, mfg_code is not None))
    if CONF_SELECT in config:
        select_ = await cg.get_variable(config[CONF_SELECT])
        cg.add(mapping.set_select(select_))
    if cluster.name != MODE_SELECT:
        cg.add(
            mapping.set_decision(
                config[CONF_DECIDE_IN_AUTOMATION],
                config[CONF_DECIDE_TIMEOUT].total_milliseconds,
            )
        )
        cg.add(mapping.set_accept_when_idle(config[CONF_ACCEPT] == "when_idle"))
    for conf in config.get(CONF_ON_CHANGE_TO_MODE, []):
        trigger = cg.new_Pvariable(conf[CONF_TRIGGER_ID])
        cg.add(mapping.add_change_trigger(trigger))
        await automation.build_automation(trigger, [(cg.uint8, "mode")], conf)


COMMAND_KEYS = (
    (CONF_ON_PAUSE, "PAUSE"),
    (CONF_ON_RESUME, "RESUME"),
    (CONF_ON_START, "START"),
    (CONF_ON_STOP, "STOP"),
    (CONF_ON_GO_HOME, "GO_HOME"),
)


async def _register_operational_state(var, endpoint_id, cluster, config):
    mapping = cg.new_Pvariable(config[CONF_ID], endpoint_id, cluster.id)
    cg.add(var.register_mapping(mapping))
    states = _resolve_states(cluster.name, config)
    for state_id, label in states["list"]:
        cg.add(mapping.add_state(state_id, label))
    for name, state_id in states["names"].items():
        cg.add(mapping.add_state_name(name, state_id))
    for alias, state in config[CONF_STATE_MAP].items():
        cg.add(
            mapping.add_state_name(
                alias, states["names"][_find_name(states["names"], state)]
            )
        )
    for name, error_id in _error_names(cluster.name).items():
        cg.add(mapping.add_error_name(name, error_id))
    for phase in config[CONF_PHASES]:
        cg.add(mapping.add_phase(phase))
    cg.add(
        mapping.set_decision(
            config[CONF_DECIDE_IN_AUTOMATION],
            config[CONF_DECIDE_TIMEOUT].total_milliseconds,
        )
    )
    for command, wanted in config[CONF_ALLOWED_STATES].items():
        for state in wanted:
            cg.add(
                mapping.add_allowed_state(
                    getattr(MatterOperationalCommand, command.upper()),
                    states["names"][_find_name(states["names"], state)],
                )
            )
    idle = config.get(CONF_IDLE_STATES)
    if idle is None:
        idle = (
            ["stopped", "docked", "charging"]
            if cluster.name == RVC_OPERATIONAL_STATE
            else ["stopped"]
        )
    for state in idle:
        cg.add(
            mapping.add_idle_state(states["names"][_find_name(states["names"], state)])
        )
    for key, attr in (
        (CONF_STATE, "state"),
        (CONF_PHASE, "phase"),
    ):
        if key in config:
            entity = await cg.get_variable(config[key])
            platform = _entity_platform_from_core(config[key])
            suffix = "select" if platform == "select" else "text_sensor"
            cg.add(getattr(mapping, f"set_{attr}_{suffix}")(entity))
    if CONF_COUNTDOWN_TIME in config:
        sensor_ = await cg.get_variable(config[CONF_COUNTDOWN_TIME])
        cg.add(mapping.set_countdown_sensor(sensor_))
    for key, command in COMMAND_KEYS:
        for conf in config.get(key, []):
            trigger = cg.new_Pvariable(conf[CONF_TRIGGER_ID])
            cg.add(
                mapping.add_command_trigger(
                    getattr(MatterOperationalCommand, command), trigger
                )
            )
            await automation.build_automation(trigger, [], conf)


def _find_name(names: dict, wanted: str) -> str:
    for name in names:
        if _normalize(name) == _normalize(wanted):
            return name
    raise KeyError(wanted)


def _entity_platform_from_core(entity_id) -> str:
    from esphome.core import CORE

    try:
        return CORE.config.get_path_for_id(entity_id)[:-1][0]
    except (KeyError, IndexError):
        return "text_sensor"


def build_attach_lines(cluster_ids: list[int]) -> list[str]:
    """C++ lines for the endpoint build callback that install the delegates (after all clusters exist)."""
    lines = []
    for cluster_id in cluster_ids:
        lines.extend(
            (
                f"if (!esphome::matter::attach_delegate(endpoint, 0x{cluster_id:04X}))",
                '  return MATTER_BUILD_FAIL("cluster delegate attach");',
            )
        )
    return lines


def layout_extras(cluster, config: dict) -> dict:
    """Attributes, commands and events that attach_delegate() guarantees (for tools/conformance)."""
    if is_mode_cluster(cluster.name):
        return {
            "attrs": ["SupportedModes", "CurrentMode"],
            # Mode Select has no ChangeToModeResponse: the SDK answers with a plain status.
            # Microwave Oven Mode disallows both commands (Mode_MicrowaveOven.xml).
            "cmds": []
            if cluster.name == "MicrowaveOvenMode"
            else ["ChangeToMode"]
            + ([] if cluster.name == MODE_SELECT else ["ChangeToModeResponse"]),
            "events": [],
        }
    if cluster.name == LAUNDRY_WASHER_CONTROLS:
        return {"attrs": [], "cmds": [], "events": []}
    commands = []
    for key, name in (
        (CONF_ON_PAUSE, "Pause"),
        (CONF_ON_RESUME, "Resume"),
        (CONF_ON_START, "Start"),
        (CONF_ON_STOP, "Stop"),
        (CONF_ON_GO_HOME, "GoHome"),
    ):
        if config.get(key):
            commands.append(name)
    if commands:
        commands.append("OperationalCommandResponse")
    return {
        "attrs": ["CountdownTime"]
        if config.get(CONF_COUNTDOWN_TIME) is not None
        else [],
        "cmds": commands,
        "events": ["OperationalError", "OperationCompletion"],
    }


def cluster_config_lines(
    cluster_name: str, config_member: str, config: dict | None
) -> list[str]:
    """Initial values the SDK config of a delegate cluster needs.

    Mode Select: the description (a fixed size char array) and the first mode as CurrentMode; the SDK does not pick one.
    Laundry Washer Controls: NumberOfRinses must start with a supported value.
    """
    if not config:
        return []
    if cluster_name == MODE_SELECT and CONF_DESCRIPTION in config:
        text = json.dumps(
            config[CONF_DESCRIPTION], ensure_ascii=False
        )  # valid C string literal
        return [
            f"strncpy({config_member}.description, {text}, sizeof({config_member}.description) - 1);",
            f"{config_member}.current_mode = {config[CONF_MODES][0][CONF_MODE]};",
        ]
    if cluster_name == LAUNDRY_WASHER_CONTROLS and CONF_RINSES in config:
        return [
            f"{config_member}.features.rinse.number_of_rinses = {RINSES[config[CONF_RINSES][0]]};"
        ]
    return []


