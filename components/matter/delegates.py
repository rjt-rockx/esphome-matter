def _error_id(names: dict[str, int]):
    """An error: name, or a (templatable) number in the manufacturer range."""

    def by_name(value):
        if isinstance(value, bool):
            raise cv.Invalid("Expected an error name or number")
        name = _snake(cv.string_strict(value))
        if name not in names:
            raise cv.Invalid(
                f"Unknown error '{value}'. Known errors: {', '.join(names)}"
            )
        return names[name]

    def by_number(value):
        number = cv.uint8_t(value)
        if number not in names.values() and not (
            MANUFACTURER_STATE_RANGE[0] <= number <= MANUFACTURER_STATE_RANGE[1]
        ):
            raise cv.Invalid(
                f"Error {number} is not a standard error; use a name or a number in "
                f"0x{MANUFACTURER_STATE_RANGE[0]:02X}-0x{MANUFACTURER_STATE_RANGE[1]:02X}"
            )
        return number

    def validate(value):
        if isinstance(value, int) and not isinstance(value, bool):
            return by_number(value)
        if isinstance(value, str) and re.fullmatch(
            r"\s*(0x[0-9a-fA-F]+|\d+)\s*", value
        ):
            return by_number(int(value, 0))
        return by_name(value)

    return validate


