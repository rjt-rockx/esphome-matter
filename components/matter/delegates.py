def _validate_operational_commands(cluster_name: str):
    def validate(config):
        if cluster_name == RVC_OPERATIONAL_STATE:
            for key in (CONF_ON_START, CONF_ON_STOP):
                if key in config:
                    raise cv.Invalid(
                        f"{key} does not exist on rvc_operational_state (the cluster has no "
                        "Start/Stop command); use the rvc_run_mode cluster to start and stop cleaning"
                    )
        elif CONF_ON_GO_HOME in config:
            raise cv.Invalid("on_go_home exists only on rvc_operational_state")
        if (CONF_ON_PAUSE in config) != (CONF_ON_RESUME in config):
            raise cv.Invalid(
                "on_pause and on_resume go together: the Matter specification makes Resume mandatory "
                "when Pause is supported and the other way around"
            )
        return config

    return validate


