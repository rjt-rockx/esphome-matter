def _validate_laundry_controls(config):
    features = list(config.get(CONF_WITH_FEATURES, []))
    # The lists need their feature; add it instead of asking for both.
    for key, feature in ((CONF_SPIN_SPEEDS, "spin"), (CONF_RINSES, "rinse")):
        if key in config and feature not in features:
            features.append(feature)
    if features:
        config[CONF_WITH_FEATURES] = features
    for feature, key in (("spin", CONF_SPIN_SPEEDS), ("rinse", CONF_RINSES)):
        if feature in features and key not in config:
            raise cv.Invalid(
                f"The {feature} feature needs `{key}:` (the values the SDK checks controller writes against)"
            )
    if CONF_SPIN_SPEED in config and CONF_SPIN_SPEEDS not in config:
        raise cv.Invalid("spin_speed needs spin_speeds")
    if CONF_NUMBER_OF_RINSES in config and CONF_RINSES not in config:
        raise cv.Invalid("number_of_rinses needs rinses")
    if len(set(config.get(CONF_SPIN_SPEEDS, []))) != len(
        config.get(CONF_SPIN_SPEEDS, [])
    ):
        raise cv.Invalid("spin_speeds must be unique")
    if len(set(config.get(CONF_RINSES, []))) != len(config.get(CONF_RINSES, [])):
        raise cv.Invalid("rinses must be unique")
    return config


def cluster_validators(cluster_name: str) -> list:
    """Cluster level validators that run after the key schema (used by ENDPOINT_SCHEMA)."""
    if cluster_name == LAUNDRY_WASHER_CONTROLS:
        return [_validate_laundry_controls]
    if cluster_name in OPERATIONAL_CLUSTERS:
        return [
            _validate_operational_commands(cluster_name),
            _validate_operational_state_map(cluster_name),
        ]
    return []


# ------------------------------------------------------------- final validation
def _entity_platform(full_config, entity_id):
    try:
        path = full_config.get_path_for_id(entity_id)[:-1]
        return path[0], full_config.get_config_for_path(path)
    except (KeyError, IndexError, TypeError):
        return None, None


def _cluster_label(endpoint_id, cluster_key):
    return f"Matter endpoint {endpoint_id} cluster '{cluster_key}'"


def validate_delegate_clusters(matter_config: dict, full_config) -> None:
    """Final validation: entity types, select options, structure-only warnings."""
    from .data_model.clusters import CLUSTERS_BY_CONF_KEY
    from .data_model.device_types import DEVICE_TYPES_BY_CONF_KEY

    actions = list(iter_matter_actions(full_config))
    for endpoint_id, endpoint_config in matter_config.get(CONF_ENDPOINTS, {}).items():
        clusters = endpoint_config.get("clusters", {})
        for cluster_key, cluster_config in clusters.items():
            cluster = CLUSTERS_BY_CONF_KEY.get(cluster_key)
            if cluster is None or not is_delegate_cluster(cluster.name):
                continue
            where = _cluster_label(endpoint_id, cluster_key)
            if not cluster.espm_available:
                raise cv.Invalid(
                    f"{where}: esp-matter 1.6 has no {cluster._name} cluster, so it can not be created"
                )
            if is_mode_cluster(cluster.name):
                _validate_mode_cluster(
                    where,
                    cluster.name,
                    cluster_config,
                    full_config,
                    sibling_state="operational_state" in clusters
                    or "rvc_operational_state" in clusters,
                )
            elif cluster.name == LAUNDRY_WASHER_CONTROLS:
                _validate_laundry_selects(where, cluster_config, full_config)
            else:
                endpoint_refs = {str(endpoint_id), str(endpoint_config.get(CONF_ID))}
                _validate_operational_cluster(
                    where, endpoint_refs, cluster, cluster_config, full_config, actions
                )
        # Delegate clusters created by a device type but not configured are structure only.
        for key in endpoint_config:
            device_type = DEVICE_TYPES_BY_CONF_KEY.get(key)
            if device_type is None:
                continue
            for cluster in device_type.server_clusters:
                if (
                    cluster.required
                    and is_delegate_cluster(cluster.name)
                    and cluster.conf_key not in clusters
                    and cluster.espm_available
                ):
                    _LOGGER.warning(
                        "Matter endpoint %s: the %s device type creates the %s cluster, which needs a "
                        "delegate to work (no ChangeToMode/Start/Pause commands without it). "
                        "Configure it under `clusters: %s:` (see docs/delegates.md)",
                        endpoint_id,
                        device_type.name,
                        cluster.name,
                        cluster.conf_key,
                    )


def _validate_mode_cluster(
    where, cluster_name, config, full_config, sibling_state=False
):
    if cluster_name == "MicrowaveOvenMode" and config.get(CONF_ON_CHANGE_TO_MODE):
        raise cv.Invalid(
            f"{where}: Microwave Oven Mode has no ChangeToMode command (Mode_MicrowaveOven.xml disallows it), so "
            "`on_change_to_mode` never runs. The mode is changed through Microwave Oven Control"
        )
    if cluster_name != MODE_SELECT:
        if config[CONF_ACCEPT] == "when_idle" and not sibling_state:
            raise cv.Invalid(
                f"{where}: `accept: when_idle` needs an operational_state or rvc_operational_state cluster on the "
                "same endpoint (its state tells whether the appliance is idle)"
            )
        has_reject = any(
            action_type == "matter.mode.reject"
            for action_type, _ in iter_matter_actions(
                {CONF_ON_CHANGE_TO_MODE: config.get(CONF_ON_CHANGE_TO_MODE, [])}
            )
        )
        if has_reject and not config[CONF_DECIDE_IN_AUTOMATION]:
            raise cv.Invalid(
                f"{where}: matter.mode.reject only works with `decide_in_automation: true` (otherwise ChangeToMode "
                "is answered before the automation runs); use `accept: when_idle` for a fixed rule"
            )
    else:
        has_reject = any(
            action_type == "matter.mode.reject"
            for action_type, _ in iter_matter_actions(
                {CONF_ON_CHANGE_TO_MODE: config.get(CONF_ON_CHANGE_TO_MODE, [])}
            )
        )
        if has_reject:
            raise cv.Invalid(
                f"{where}: the SDK answers ChangeToMode of Mode Select itself, matter.mode.reject has no effect"
            )
    if CONF_SELECT in config:
        _platform, entity = _entity_platform(full_config, config[CONF_SELECT])
        options = (entity or {}).get("options")
        if options:
            missing = [
                mode[CONF_OPTION]
                for mode in config[CONF_MODES]
                if mode[CONF_OPTION] not in options
            ]
            if missing:
                raise cv.Invalid(
                    f"{where}: the select '{config[CONF_SELECT]}' has no option {missing!r}. Every mode "
                    "needs a select option with the same text as its label, or an explicit `option:`. "
                    f"Select options: {list(options)!r}"
                )


def _validate_laundry_selects(where, config, full_config):
    for key, values in (
        (CONF_SPIN_SPEED, config.get(CONF_SPIN_SPEEDS, [])),
        (CONF_NUMBER_OF_RINSES, config.get(CONF_RINSES, [])),
    ):
        if key not in config:
            continue
        _platform, entity = _entity_platform(full_config, config[key])
        options = (entity or {}).get("options")
        if options:
            if key == CONF_SPIN_SPEED:
                unknown = [option for option in options if option not in values]
            else:
                unknown = [option for option in options if _snake(option) not in values]
            if unknown:
                raise cv.Invalid(
                    f"{where}: select '{config[key]}' has options {unknown!r} that are not in "
                    f"`{CONF_SPIN_SPEEDS if key == CONF_SPIN_SPEED else CONF_RINSES}` ({list(values)!r})"
                )


def _validate_operational_cluster(
    where, endpoint_refs, cluster, config, full_config, actions
):
    for key in (CONF_STATE, CONF_PHASE):
        if key not in config:
            continue
        platform, entity = _entity_platform(full_config, config[key])
        if platform not in ("select", "text_sensor"):
            raise cv.Invalid(
                f"{where}: `{key}` must be a select or a text_sensor, but '{config[key]}' is "
                f"{'a ' + platform if platform else 'not a known entity'}"
            )
        if key == CONF_STATE and platform == "select":
            options = (entity or {}).get("options")
            if options:
                available = set(_resolve_states(cluster.name, config)["names"]) | set(
                    config[CONF_STATE_MAP]
                )
                names = {_normalize(name) for name in available}
                unknown = [
                    option for option in options if _normalize(option) not in names
                ]
                if unknown:
                    raise cv.Invalid(
                        f"{where}: select options {unknown!r} are not operational states. Name them like "
                        f"the states ({', '.join(_resolve_states(cluster.name, config)['names'])}) or map "
                        "them with `state_map: {option: state}`"
                    )
        if key == CONF_PHASE and platform == "select":
            options = (entity or {}).get("options")
            if options:
                unknown = [
                    option
                    for option in options
                    if _normalize(option)
                    not in {_normalize(p) for p in config[CONF_PHASES]}
                    and _normalize(option) not in ("none", "null")
                ]
                if unknown:
                    raise cv.Invalid(
                        f"{where}: select options {unknown!r} are not in `phases`"
                    )
    has_action = False
    for action_type, action in actions:
        if action_type in (
            "matter.operational_state.set",
            "matter.operational_state.error",
            "matter.operational_state.completed",
        ):
            endpoint = action.get(CONF_ENDPOINT)
            if str(endpoint) in endpoint_refs:
                has_action = True
    if CONF_STATE not in config and not has_action:
        _LOGGER.warning(
            "%s has no `state` source and no matter.operational_state.set action; the operational state "
            "will stay Stopped",
            where,
        )


