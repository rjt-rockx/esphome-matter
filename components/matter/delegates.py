"""Delegate layer: Mode Base derived clusters, Mode Select, Operational State and RVC Operational State.

These clusters are driven by an application delegate in connectedhomeip. Without one they exist in the data model but
cannot be operated (no ChangeToMode / Start / Pause commands, empty SupportedModes). This module turns YAML into the
C++ objects in matter_modes.cpp / matter_operational_state.cpp:

    clusters:
      laundry_washer_mode:
        modes: [...]            # label, mode number, semantic tags
        select: washer_program  # two-way binding to an ESPHome select
        on_change_to_mode: ...  # automation with the requested mode; matter.mode.reject vetoes
      operational_state:
        phases: [...]
        state: washer_state     # select or text sensor
        on_start / on_stop / on_pause / on_resume / on_go_home

See docs/delegates.md. The data (tags, status codes, states, errors) comes from
data_model/delegate_data.json, generated by tools/gen_delegate_data.py.
"""

