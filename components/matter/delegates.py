def _tag_validator(cluster_name: str):
    """Validates one entry of `tags:`; returns a dict(value, mfg_code | None, named)."""
    known = (
        {}
        if cluster_name == MODE_SELECT
        else DATA["mode_clusters"][cluster_name]["tags"]
    )
    by_value = {value: name for name, value in known.items()}

    def validate(value):
        if isinstance(value, dict):
            if cluster_name == MODE_SELECT:
                schema = {
                    cv.Required(CONF_MFG_CODE): cv.int_range(min=0, max=0xFFFF),
                    cv.Required(CONF_VALUE): cv.int_range(min=0, max=0xFFFF),
                }
            else:
                schema = {
                    cv.Required(CONF_MFG_CODE): cv.int_range(min=1, max=0xFFFE),
                    cv.Required(CONF_VALUE): cv.int_range(min=0, max=0xFFFF),
                }
            value = cv.Schema(schema)(value)
            return {
                "value": value[CONF_VALUE],
                "mfg_code": value[CONF_MFG_CODE],
                "named": False,
            }
        if cluster_name == MODE_SELECT:
            raise cv.Invalid(
                "Mode Select semantic tags need a manufacturer code and a value: "
                "{mfg_code: 0xFFF1, value: 1}"
            )
        if isinstance(value, bool):
            # YAML 1.1 reads an unquoted on/off as a boolean (the "off" tag of the Water Heater Mode).
            value = "on" if value else "off"
        if isinstance(value, int):
            tag_value = cv.int_range(min=0, max=0xFFFF)(value)
            if tag_value in by_value:
                return {"value": tag_value, "mfg_code": None, "named": True}
            if MFG_TAG_RANGE[0] <= tag_value <= MFG_TAG_RANGE[1]:
                return {"value": tag_value, "mfg_code": None, "named": False}
            raise cv.Invalid(
                f"Tag 0x{tag_value:04X} is neither a {cluster_name} tag nor in the manufacturer range "
                "0x8000-0xBFFF; use a tag name, or {mfg_code: <vendor id>, value: <number>}"
            )
        name = _snake(cv.string_strict(value))
        if name not in known:
            raise cv.Invalid(
                f"Unknown {cluster_name} tag '{value}'. Known tags: {', '.join(known)}"
            )
        return {"value": known[name], "mfg_code": None, "named": True}

    return validate


def _mode_entry_schema(cluster_name: str):
    is_select = cluster_name == MODE_SELECT
    max_tags = MAX_SELECT_TAGS if is_select else MAX_MODE_TAGS
    tags_key = (
        cv.Optional(CONF_TAGS, default=[]) if is_select else cv.Required(CONF_TAGS)
    )
    return cv.Schema(
        {
            cv.Required(CONF_LABEL): _utf8_label,
            cv.Optional(CONF_MODE): cv.int_range(min=0, max=255),
            tags_key: cv.All(
                cv.ensure_list(_tag_validator(cluster_name)),
                cv.Length(min=0 if is_select else 1, max=max_tags),
            ),
            cv.Optional(CONF_OPTION): cv.string_strict,
        }
    )


def _validate_modes(cluster_name: str):
    def validate(modes):
        resolved = []
        for index, mode in enumerate(modes):
            mode = dict(mode)
            mode.setdefault(CONF_MODE, index)
            mode.setdefault(CONF_OPTION, mode[CONF_LABEL])
            resolved.append(mode)
        numbers = [mode[CONF_MODE] for mode in resolved]
        if len(set(numbers)) != len(numbers):
            raise cv.Invalid(
                "Mode numbers must be unique; give the modes explicit `mode:` numbers "
                "(modes without one use their position in the list)"
            )
        labels = [mode[CONF_LABEL] for mode in resolved]
        if len(set(labels)) != len(labels):
            raise cv.Invalid("Mode labels must be unique")
        if cluster_name == MODE_SELECT:
            return resolved
        known = DATA["mode_clusters"][cluster_name]["tags"]
        by_value = {value: name for name, value in known.items()}
        names_per_mode = []
        for mode in resolved:
            tags = mode[CONF_TAGS]
            keys = [(tag["value"], tag["mfg_code"]) for tag in tags]
            if len(set(keys)) != len(keys):
                raise cv.Invalid(f"Mode '{mode[CONF_LABEL]}' lists a tag twice")
            if not any(tag["named"] for tag in tags):
                raise cv.Invalid(
                    f"Mode '{mode[CONF_LABEL]}' needs at least one {cluster_name} tag "
                    "(a name from the Matter specification, not only manufacturer tags)"
                )
            names = {
                by_value[tag["value"]]
                for tag in tags
                if tag["named"] and tag["mfg_code"] is None
            }
            names_per_mode.append((mode[CONF_LABEL], names))
            for group in EXCLUSIVE_TAG_GROUPS.get(cluster_name, ()):
                if len(names & set(group)) > 1:
                    raise cv.Invalid(
                        f"Mode '{mode[CONF_LABEL]}' combines {', '.join(sorted(names & set(group)))}; "
                        f"at most one of {', '.join(group)} may be used per mode"
                    )
            for tag, others in CONFLICTING_TAGS.get(cluster_name, ()):
                if tag in names and names & set(others):
                    raise cv.Invalid(
                        f"Mode '{mode[CONF_LABEL]}': tag {tag} can not be combined with "
                        f"{', '.join(sorted(names & set(others)))}"
                    )
        all_names = set().union(*(names for _, names in names_per_mode))
        for group in REQUIRED_TAG_GROUPS.get(cluster_name, ()):
            if not all_names & set(group):
                raise cv.Invalid(
                    f"The Matter specification requires {cluster_name} to have a mode with the "
                    f"'{' or '.join(group)}' tag"
                )
        return resolved

    return validate


def _change_trigger_schema():
    return automation.validate_automation(
        {cv.GenerateID(CONF_TRIGGER_ID): cv.declare_id(MatterChangeToModeTrigger)}
    )


def _mode_cluster_schema(cluster_name: str) -> dict:
    is_select = cluster_name == MODE_SELECT
    schema = {
        cv.GenerateID(): cv.declare_id(
            MatterModeSelectMapping if is_select else MatterModeMapping
        ),
        cv.Required(CONF_MODES): cv.All(
            cv.ensure_list(_mode_entry_schema(cluster_name)),
            # Mode Select may have a single mode; the Mode Base clusters need two or more.
            cv.Length(min=1 if is_select else 2, max=255),
            _validate_modes(cluster_name),
        ),
        cv.Optional(CONF_SELECT): cv.use_id(select.Select),
        cv.Optional(CONF_ON_CHANGE_TO_MODE): _change_trigger_schema(),
    }
    if is_select:
        schema[cv.Required(CONF_DESCRIPTION)] = _utf8_label
    else:
        # The SDK answers ChangeToMode of Mode Select itself, so these only exist on the Mode Base clusters.
        schema[cv.Optional(CONF_ACCEPT, default="always")] = cv.one_of(
            "always", "when_idle", lower=True
        )
        schema[cv.Optional(CONF_DECIDE_IN_AUTOMATION, default=False)] = cv.boolean
        schema[cv.Optional(CONF_DECIDE_TIMEOUT, default=DEFAULT_DECIDE_TIMEOUT)] = (
            cv.positive_time_period_milliseconds
        )
    return schema


