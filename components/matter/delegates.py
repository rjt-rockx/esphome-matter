def _snake(value: str) -> str:
    return re.sub(r"[\s\-]+", "_", str(value).strip()).lower()


def _normalize(value: str) -> str:
    """Same normalization as MatterOperationalStateMapping::normalize_."""
    return re.sub(r"[_\s\-]+", "", str(value)).lower()


def is_mode_cluster(cluster_name: str) -> bool:
    return cluster_name in MODE_CLUSTERS or cluster_name == MODE_SELECT


def is_delegate_cluster(cluster_name: str) -> bool:
    return (
        is_mode_cluster(cluster_name)
        or cluster_name in OPERATIONAL_CLUSTERS
        or cluster_name == LAUNDRY_WASHER_CONTROLS
    )


def _utf8_label(value):
    value = cv.string_strict(value)
    if not value:
        raise cv.Invalid("label must not be empty")
    if len(value.encode()) > MAX_LABEL_BYTES:
        raise cv.Invalid(
            f"label is {len(value.encode())} bytes, the maximum is {MAX_LABEL_BYTES}"
        )
    return value


